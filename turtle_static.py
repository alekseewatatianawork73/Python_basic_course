# Модуль turtle: рисуем с черепашкой
# ============================================================
import turtle as tr  # подключение библиотеки с набором команд


# ============================================================
# 1. Создание окна для рисования
# ============================================================

screen = tr.Screen()  # создаём окно и сохраняем его в переменную screen.
screen.setup(1000, 800)  # размер окна 1000x800: ширина и высота в пикселях.
screen.title("Знакомство с библиотекой turtle")  #  заголовок окна
screen.bgcolor("white")  # задаём цвет фона (на английском, строчными буквами)


# ============================================================
# 2. Создание курсора для рисования на экране (создание черепашки)
# ============================================================

tur = tr.Turtle()  # создаём объект-черепашку и сохраняем его в переменную tur - это наша "кисть".
tur.shape("turtle")  # задаём форму курсора-кисти
# Форма курсора: "arrow" - стрелка, "turtle" - черепашка, "circle" - круг, "square" - квадрат, "triangle" - треугольник, "classic" - курсор.

tur.speed(3)  # скорость рисования: от 1 — медленно до 10 — быстро (0 - мгновенно)
tur.pensize(5)  # толщина линии в пикселях
tur.pencolor('blue')  # цвет линии

# ============================================================
# 3. Примеры рисунков
# ============================================================

# Перемещение к месту рисунка
tur.penup()  # поднимаем кисть, чтобы перейти к месту рисунка без линии (делаем линию невидимой)
tur.goto(-430, 290)  # перемещаемся в точку с координатами x = -430, y = 290.
tur.pendown()  # опускаем кисть - дальнейшие перемещения черепашки оставляют линию, можно рисовать

# рисуем квадрат (нужно повторить движение вперёд и поворот на 90 градусов 4 раза для каждой стороны)
for i in range(4):
    tur.forward(100)  # двигаемся вперёд на 100 пикселей (одна сторона)
    tur.left(90)  # в конце поворачиваем кисть влево на 90 градусов

# --------------------------------------------------------------------------------

tur.penup()  # поднимаем кисть - делаем линию невидимой
tur.goto(-250, 390)  # перемещаемся в точку
tur.pendown()  # опускаем кисть - можно рисовать

tur.pencolor('red')  # цвет линии - красный

# рисуем пятиугольник (нужно повторить движение вперёд и поворот на 72 градуса 5 раз для каждой стороны)
for i in range(5):
    tur.forward(100)  # двигаемся вперёд на 100 пикселей (одна сторона)
    tur.right(72)  # в конце поворачиваем кисть вправо на 72 градуса

# --------------------------------------------------------------------------------

tur.penup()  # поднимаем кисть - делаем линию невидимой
tur.goto(-100, 320)  # перемещаемся в точку
tur.pendown()  # опускаем кисть - можно рисовать

# рисуем звезду (идём по вершинам пятиугольника не к соседней вершине, а перескакивая через одну => угол 72 * 2 = 144)
for i in range(5):
    tur.forward(100)  # двигаемся вперёд на 100 пикселей (одна сторона)
    tur.right(144)  # в конце поворачиваем кисть вправо на 144 градуса

# --------------------------------------------------------------------------------

tur.penup()  # поднимаем кисть - делаем линию невидимой
tur.goto(-430, 220)  # перемещаемся в точку
tur.pendown()  # опускаем кисть - можно рисовать

tur.pencolor('green')  # цвет линии - зелёный

# семиугольная звезда (угол семиугольника 360 / 7 => угол звезды (360 / 7) * 2 = 720 / 7)
for i in range(7):
    tur.forward(200)  # двигаемся вперёд на 200 пикселей (одна сторона)
    tur.right(720 / 7)  # в конце поворачиваем кисть вправо


tur.penup()  # поднимаем кисть - делаем линию невидимой
tur.home()  # возвращаем кисть в исходное положение (0, 0) - центр экрана
tur.pendown()  # опускаем кисть - можно рисовать

# --------------------------------------------------------------------------------

# создадим новую кисть
cir = tr.Turtle()
cir.shape("circle")  # форма кисти - круг
cir.pensize(3)  # толщина - 3 пикселя
cir.speed(5)  # скорость рисования - 5 пикселей

# Рисуем домик: светло-зелёная крыша-треугольник и тёмно-зелёный дом-квадрат, контур - фиолетовый

cir.pencolor('purple')  # цвет линии - фиолетовый

# КРЫША
cir.fillcolor('lightgreen')  # цвет заливки
cir.begin_fill()  # начало заливки

for i in range(3):
    cir.forward(200)  # сторона треугольника (крыши)
    cir.left(120)  # угол треугольника (рисуем влево)

cir.end_fill()  # конец заливки

# ДОМ
cir.fillcolor('darkgreen')  # цвет заливки
cir.begin_fill()  # начало заливки

for i in range(4):
    cir.forward(200)  # сторона квадрата-дома (совпадает с крышей)
    cir.right(90)  # в конце поворачиваем вправо (дом ниже крыши => поворот вниз)

cir.end_fill()  # конец заливки


# Добавим круглое жёлтое окно в середине домика

cir.penup()  # поднимаем кисть - делаем линию невидимой
# Левый верхний угол квадрата в координатах (0, 0), длина стороны 200 => середина (100, -100)
# Радиус окна 50 пикселей => отступим от середины вверх на 50 по вертикали (по y)
cir.goto(100, -50)  # координаты середины дома-квадрата
cir.pendown()  # опускаем кисть - можно рисовать

cir.fillcolor('yellow')  # цвет заливки
cir.begin_fill()  # начало заливки

cir.circle(-50)  # рисуем окружность радиусом 50 пикселей (рисуется вправо, потому что минус; без минуса - влево)

cir.end_fill()  # конец заливки


# ============================================================
# Запускаем бесконечный цикл для отображения окна при помощи метода done()
tr.done()
