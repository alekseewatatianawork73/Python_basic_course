# Пример: нужно наполнить 3 коробки. В каждую коробку помещается по 4 кубика.
# Берём первую коробку — кладём все 4 кубика. Потом вторую — снова 4. Потом третью — ещё 4.
# То есть для каждой из 3-х коробок мы повторим перекладывание нового кубика 4 раза.

# 1) Сначала переберём в цикле только коробки
for box_num in range(1, 4):  # номер коробки box_num изменяется от 1 до 3
    print(f'Открыли коробку номер {box_num}')
    # здесь заполняем коробку номер box кубиками
    print(f'Коробка номер {box_num} заполнена')


# 2) Теперь в каждую коробку будем складывать кубики
for box_num in range(1, 4):  # номер коробки box изменяется от 1 до 3
    print(f'Открыли коробку номер {box_num}')

    for cube in range(1, 5):  # в каждую коробку кладём кубики с номерами от 1 до 4
        print(f'Положили в коробку номер {box_num} кубик номер {cube}')

    print(f'Коробка номер {box_num} заполнена')


