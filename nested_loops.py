# 4. Как индексы (позиции) строк и столбцов изменяются для каждого элемента?

n = int(input())
# перебираем номера всех строк и столбцов от 1 до n
for i in range(1, n + 1):
    for j in range(1, n + 1):
        # выводим номер строки i и номер столбца j в формате (i, j)
        print(f'({i}, {j})', end=' ')
    print()  # переходим на новую строку


# 5. Выводим нули только на главной диагонали. В остальных случаях - звёздочки.
n = int(input())
for i in range(1, n + 1):
    for j in range(1, n + 1):
        # проверяем, что находимся на главной диагонали
        if i == j:
            print('0', end=' ')
        else:
            print('*', end=' ')
    print()  # переходим на новую строку


# 6. Выводим нули только в чётных столбцах. В остальных случаях - звёздочки.
n = int(input())
for i in range(1, n + 1):
    for j in range(1, n + 1):
        # проверяем, что номер столбца - чётный
        if j % 2 == 0:
            print('0', end=' ')
        else:
            print('*', end=' ')
    print()  # переходим на новую строку


# 7. Заполняем нулями только строку, расположенную посередине. В остальных случаях - звёздочки.
n = int(input())
# перебираем номера всех строк и столбцов от 0 до n - 1
for i in range(n):
    for j in range(n):
        # проверяем, что находимся в средней строке
        if i == n // 2:
            print('0', end=' ')
        else:
            print('*', end=' ')
    print()  # переходим на новую строку
