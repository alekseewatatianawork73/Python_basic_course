# 1. Таблица умножения для всех чисел от 1 до k

# Для одного числа k
k = int(input())
# в цикле меняем второй множитель i от 1 до 10 как в таблице умножения
for i in range(1, 11):
    # здесь наше число k будет умножаться по порядку на каждое значение i
    # выделили под каждое число по 3 позиции, чтобы они располагались ровно
    print(f'{k:>3} * {i:<3} = {k * i:>3}')

# Для всех чисел от 1 до k
k = int(input())
# в цикле также меняем второй множитель i от 1 до 10 как в таблице умножения
for i in range(1, 11):
    # далее перебираем все числа, которые нужно умножать (от 1 до k)
    for number in range(1, k + 1):
        # здесь каждое число k будет умножаться по порядку на значение i (от 1 до 10)
        print(f'{number:>3} * {i:<3} = {number * i:>3}', end = ' | ')
        # выделили под каждое число по 3 позиции, чтобы они располагались ровно
        # между столбиками добавили черту для имитации таблицы

    print()  # переход на новую строку после завершения умножения чисел на текущее значение i



# 2. Числовой флаг: Требуется нарисовать числовой флаг, в котором будет N строк и M столбцов.
# В 1-ой строке будем выводить единицы, во 2-ой – двойки, в 3-ей – тройки и т.д.
# В последней N-ой строке будут выводиться числа N.

n = int(input())  # получаем количество строк
m = int(input())  # получаем количество столбцов

# перебираем номера всех строк от 1 до n
for i in range(1, n + 1):
    # перебираем номера всех элементов в строке (т.е. всех столбцов) от 1 до m
    for j in range(1, m + 1):
        print(i, end = ' ')  # выводим элементы в одной строке через пробел
    # когда строка закончилась, нужно перейти на новую строку
    # для этого используем пустую команду print() - она сработает как клавиша Enter
    print()


# 3. Звёздный флаг: выводим квадрат размером nxm из звёздочек
n, m = int(input()), int(input())

# перебираем номера всех строк от 1 до n
for i in range(1, n + 1):
    # выводим в каждой строке m звёздочек через пробел
    for j in range(1, m + 1):
        print('*', end=' ')
    # переходим на новую строку
    print()

