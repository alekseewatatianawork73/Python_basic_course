# Классический пример: электронные часы
# В одном дне 24 часа, номер часа меняется 24 раза => внешний цикл повторится 24 раза
# В одном часе 60 минут => первый внутренний цикл повторится 60 раз для каждого часа hour
# В одной минуте 60 секунд => второй внутренний цикл повторится 60 раз для каждой минуты minute
for hour in range(24):
    print(f'Идёт {hour}-й час')
    # для этого часа выводим все прошедшие минуты
    for minute in range(60):
        print(f'Идёт {minute}-я минута')
        # для этой минуты выводим все прошедшие секунды
        for second in range(60):
            print(f'Время: {hour} : {minute} : {second}')

