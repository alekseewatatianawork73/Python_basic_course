# Раздел 1.3. Задача "Строка vs Число
# Нам дано два значения => две команды input()
a = input()  # получили строку - набор символов
b = input()  # получили строку - набор символов

scl = a + b  # => результат склейки двух строк

# Чтобы сделать строку числом, можно применить функцию int()
sm = int(a) + int(b)  # => результат сложения двух целых чисел

# выводим результаты через пробел => в одной команде print() через запятую
print(sm, scl)

# Примеры неверных решений:
#1
a = 5
b = 7
print(a + b, '57')  # => программа работает только для чисел 5 и 7!

#2
a = int(input())
b = int(input())
print(a + b)
c = input()
d = input()
print(c + d)  # по задаче дано только два значения, здесь же input() используется 4 раза!

