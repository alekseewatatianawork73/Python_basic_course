# Раздел 1.2. Задача "Знакомство"
name = input()  # вводится одна строка - имя человека => используем input()

# Вывести сообщение можно несколькими способами:
print('Привет! Меня зовут ' + name)  # => при помощи оператора +
                                    # (при сложении строки склеиваются)

print('Привет! Меня зовут', name)  # => при помощи свойства команды print
                                # (элементы, указанные в print() через запятую, выводятся через пробел)

print(f'Привет! Меня зовут {name}')  # => при помощи f-строки
                                # (переменную можно указывать прямо внутри текста)

# Примеры неверных решений:
print('Привет! Меня зовут' + name)  # => не хватает пробела - имя приклеится к слову "зовут"
print('Привет! Меня зовут ', name)  # => пробел лишний - запятая в print() уже означает пробел между значениями
print(f'Привет! Меня зовут name')  # => переменные долны указываться в фигурных скобках, чтобы выводилось их значение

