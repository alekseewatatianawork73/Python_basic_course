# Раздел 1.2. Задача "Который час?"
# Дано два значения - часы и минуты => используем input() дважды для каждой строки со значением:
h = input()  # => создали переменную для часов и сохранили туда первое значение
m = input()  # => создали переменную для минут и сохранили туда следующее значение

# Вывести время в нужном формате можно несколькими способами:
print(h + ':' + m)  # склеиваем строки при помощи оператора +
print(h, m, sep=':')  # => используем разделитель sep - он заменит пробел между значениями на двоеточие
print(f'{h}:{m}')  # => используем f-строку - здесь двоеточие это часть текста (без фигурных скобок)
                    # а переменные h и m по правилам f-строк указываются внутри фигурных скобок

# Примеры неверных решений:
print(h + m, sep=':')  # => часы и минуты просто склеиваются знаком +, sep не работает для одного элемента
print(f'h:m')  # => h и m без фигурных скобок считаются обычными символами,
                # поэтому вместо их значений получим "h:m"
print(10, 15, sep=':')  # программа для любых введённых значений будет выводить 10:15

