S = float(input())
print(f"Здравствуйте, {NAME}! Ваша поездка продлится {D} дней. К оплате: {S} рублей.")

#2. Не совсем правильное решение
NAME = input()
D = input()
S = input()
print(f"Здравствуйте, {NAME}! Ваша поездка продлится {D} дней. К оплате: {S} рублей.")

# Во втором решении и имя, и возраст, и стоимость вводятся как строки,
# то есть если мы, например, в качестве возраста введём не целое число, а набор букв,
# то программа не выведет ошибку, хотя должна, ведь возраст может быть только числом, как и стоимость.
# Поэтому более точным будет первое решение.

