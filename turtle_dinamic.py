# Модуль turtle: интерактивные функции
# ============================================================
import turtle


# ============================================================
# 1. Создание окна и черепашки
# ============================================================

# Создаём окно и сохраняем его в переменную screen
screen = turtle.Screen()
screen.setup(900, 700)  # размеры окна в пикселях
screen.title("Интерактивные функции turtle")  # заголовок окна
screen.bgcolor("lightblue")  # цвет фона окна

# Создаём черепашку tur
tur = turtle.Turtle()
tur.shape("turtle")  # форма курсора - черепашка
tur.speed(5)  # скорость рисования
tur.pencolor("darkgreen")  # цвет линии.
tur.pensize(3)  # толщина линии

# В начале черепашка находится в точке (0, 0) и смотрит направо.


# ============================================================
# 2. Создаём функции - кусочки кода со своим названием, которые мы будем дальше использовать
# ============================================================

# Функция — это блок кода с именем. Её можно вызывать (запускать) много раз из разных частей программы.

# Функция, которая рисует квадрат.
def draw_square():
    for i in range(4):
        tur.forward(80)
        tur.left(90)


# Функция, которая рисует треугольник.
def draw_triangle():
    for i in range(3):
        tur.forward(80)
        tur.left(120)


# Функции создаются в начале программы, а вызываются позже, когда они нужны.


# ============================================================
# 3. Функции для движения черепашки в разные стороны и поворота вправо и влево
# ============================================================

def forw():
    tur.forward(10)


def backw():
    tur.backward(10)


def to_left():
    tur.left(90)


def to_right():
    tur.right(90)


# ============================================================
# 4. Функции для смены темы экрана
# ============================================================

# Функция, которая включает тёмную тему.
def set_dark_theme():
    screen.bgcolor("darkblue")
    tur.pencolor("lightgreen")
    tur.clear()


# Функция, которая включает светлую тему.
def set_light_theme():
    screen.bgcolor("lightblue")
    tur.pencolor("darkgreen")
    tur.clear()


# ============================================================
# 5. Функции для мыши
# ============================================================

# Функция перемещает черепашку в точку клика. Координаты x и y становятся известными при клике по окну.
def move_to_click(x, y):
    tur.penup()
    tur.goto(x, y)
    tur.pendown()


# Функция, которая рисует ступеньку.
def draw_step(x, y):
    tur.forward(50)
    tur.left(90)
    tur.forward(50)
    tur.right(90)


# ============================================================
# 6. Подключаем кнопки клавиатуры
# ============================================================

# Включаем режим прослушивания действий пользователя. Без этой команды нажатия клавиш не будут обрабатываться.
screen.listen()

# Стрелки клавиатуры управляют перемещением черепашки.
screen.onkeypress(forw, "Up")
screen.onkeypress(backw, "Down")
screen.onkeypress(to_left, "Left")
screen.onkeypress(to_right, "Right")

# При нажатии и удержании стрелки черепашка будет продолжать движение.

# Клавиши для рисования фигур.
screen.onkey(draw_square, "s")
screen.onkey(draw_triangle, "t")

# Клавиши для смены темы.
screen.onkey(set_dark_theme, "d")
screen.onkey(set_light_theme, "l")


# ============================================================
# 7. Подключаем кнопки мыши
# ============================================================

# При клике в любом месте окна черепашка перемещается в точку клика.
screen.onscreenclick(move_to_click)

# При клике по самой черепашке рисуется ступенька.
tur.onclick(draw_step)


# Запускаем обработку событий окна.
turtle.done()
