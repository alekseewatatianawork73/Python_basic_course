# Поиск делителей числа
n = int(input())
d = 1  # первый наименьший делитель числа
# перебираем числа от 1 до n, так как делитель не может быть больше делимого
while d <= n:
    # проверяем, что наше число n делится на заданное d
    if n % d == 0:
        print(d)
    d += 1  # переходим к следующему возможному делителю

# решение 2: перебор до половины числа
n = int(input())
d = 1  # первый наименьший делитель числа
# перебираем числа от 1 до n/2
while d <= n // 2:
    if n % d == 0:
        print(d)
    d += 1  # переходим к следующему возможному делителю

# решение 3: перебор до корня из числа
n = int(input())
d = 1  # первый наименьший делитель числа
# перебираем все делители d, такие, что d * d <= n
while d * d <= n:  # или while d <= N**0.5
    if n % d == 0:
        print(d)
    d += 1  # переходим к следующему возможному делителю
