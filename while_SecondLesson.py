# Рассмотрим задачу. На столе лежат три кубика. Робот перекладывает их в коробку по одному.

# 1) Пока на столе есть кубики, нужно перекладывать по одному.
cubes = 3

while cubes > 0:
    print("Переложили один кубик")
    cubes = cubes - 1

print("На столе больше нет кубиков")

# 2) Если на столе есть кубики, нужно переложить один.
cubes = 3

if cubes > 0:
    print("Переложили один кубик")
    cubes = cubes - 1

print("Осталось кубиков:", cubes)

