# Аналогия с подъёмом по леснице и переходом на следующий этаж:

final_etazh = int(input())  # => количество этажей в доме (целое)
now_etazh = 1  # => первый этаж, с него начинаем идти

print('Начинаем подъём')
# пока не дойдём до последнего этажа, поднимаемся
while now_etazh <= final_etazh:
    print(f'Я сейчас на {now_etazh} этаже')
    now_etazh += 1  # => переходим на следующий этаж

print('Подъём окончен')

