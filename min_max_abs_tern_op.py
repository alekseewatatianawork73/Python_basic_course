# Тернарный оператор: значение1 if условие else значение2

# Пример: является ли число чётным
n = int(input())
if n % 2 == 0:
    print('Чётное число')
else:
    print('Нечётное число')

# Решение через тернарный оператор
n = int(input())
answer = 'Чётное число' if n % 2 == 0 else 'Нечётное число'
print(answer)

# Или без переменной answer
n = int(input())
