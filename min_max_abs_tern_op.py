# Алгоритмы с ветвлениями.
# Встроенные функции для поиска минимума, максимума, модуля.
#-------------------------------------------------------------------------

#1.1. Алгоритм поиска модуля
x = int(input())
# если число отрицательное - заменяем на противоположное
if x < 0:
    x = -x
print(x)

#1.2. Решение через функцию abs()
x = int(input())
# найдём модуль числа x и сохраним в переменную m
m = abs(x)
print(m)

#-------------------------------------------------------------------------

a = int(input())
b = int(input())
c = int(input())

#2.1. Алгоритм поиска максимума
if a >= b and a >= c:
    print(a)
elif b >= c and b >= a:
    print(b)
else:
    print(c)

# Или если нужна переменная для максимума
mx = a
if b > mx:
    mx = b
if c > mx:
    mx = c
print(mx)

#2.2. Решение через функцию max()
a, b, c = map(int, input().split())
mx = max(a, b, c)
print(mx)

#-------------------------------------------------------------------------

#3.1. Алгоритм поиска минимума
if a <= b and a <= c:
    print(a)
elif b <= c and b <= a:
    print(b)
else:
    print(c)

# Или если нужна переменная для минимума
mn = a
if b < mn:
    mn = b
if c < mn:
    mn = c
print(mn)

#3.2. Решение через функцию min()
a, b, c = map(int, input().split())
mn = min(a, b, c)
print(mn)


