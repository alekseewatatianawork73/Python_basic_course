# Алгоритм поиска цифр числа

# --------------------------------------------------------------------------------
# Запрашиваем у пользователя трёхзначное число
n = int(input("Введите трёхзначное число: "))

# Выделяем последнюю цифру числа
# Остаток от деления на 10 даёт последнюю цифру
a = n % 10

# Выделяем среднюю цифру числа
# Сначала убираем последнюю цифру (// 10),
# затем берём последнюю из оставшихся (% 10)
b = n // 10 % 10

# Выделяем первую цифру числа
# Целочисленное деление на 100 даёт первую цифру
c = n // 100

# Выводим полученные цифры
print("Первая цифра:", c)
print("Вторая цифра:", b)
print("Третья цифра:", a)

# --------------------------------------------------------------------------------
# Вводим пятизначное число
n = int(input("Введите пятизначное число: "))

# Выделяем цифры, начиная с последней
a = n % 10                # пятая (последняя) цифра
b = n // 10 % 10          # четвёртая цифра
c = n // 100 % 10         # третья цифра
d = n // 1000 % 10        # вторая цифра
e = n // 10000            # первая цифра

# Выводим цифры в порядке слева направо
print("Первая цифра:", e)
print("Вторая цифра:", d)
print("Третья цифра:", c)
print("Четвёртая цифра:", b)
print("Пятая цифра:", a)

print("Сумма цифр:", a + b + c + d + e)

