# Задача. Даны числа A и B. Необходимо вывести все числа от A до B, которые не делятся на 3.
a, b = map(int, input().split())
# создаём переменную, в которой будем считать количество
count = 0  # ещё не нашли ни одного числа => ноль
k = a  # начинаем проверку с первого числа A
while k <= b:  # идём до B
    # если находим число, не кратное 3, то количество становится больше на 1
    if k % 3 != 0:
        count = count + 1
    k = k + 1  # переходим к следующему числу

