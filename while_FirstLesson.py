# Задача. Даны числа A и B. Необходимо вывести все числа от A до B через пробел.
a, b = map(int, input().split())
k = a  # начинаем с первого числа A
while k <= b:  # идём до B
    print(k, end=' ')  # выводим текущее число и вместо перехода на новую строку ставим пробел
    k = k + 1  # переходим к следующему числу


