#-----------------------------------------------------------------------------------------------------
# Рассмотрим задачу. Дано число n, требуется вывести все числа от 1 до n на экран
n = int(input())
# будем последовательно выводить n на экран, а после переходить к предыдущему числу, уменьшая n на 1
print(n)
n = n - 1
print(n)
n = n - 1
print(n)
n = n - 1
# Когда же стоит остановиться? => Нужна проверка (условие) - когда дойдём до нуля, нужно остановить программу
# Исправленное решение:
print(n)
n = n - 1
if n == 0:
    exit()

print(n)
n = n - 1
if n == 0:
    exit()

print(n)
n = n - 1
if n == 0:
    exit()
# И так нужно повторить эти действия много раз, чобы учесть множество значений n - это неэффективно
# В Python есть конструкция, которая позволяет повторять действия,
# пока условие остаётся верным (в нашем случае пока n > 0) - цикл while (пока)

# Решение через цикл:
n = int(input())
while n > 0:  # пока n > 0 повторяем действия, записанные с отступом; если условие стало неверным, прекращаем повторение
    print(n)
    n = n - 1
print('Конец цикла')

