# Задача. Дано число N. Требуется вывести все числа от 1 до N (не включительно), кратные 5.
n = int(input())
k = 1  # начинаем проверять числа с единицы
# повторяем действия, пока не дойдём до n => пока k <= n
while k <= n:
    # выводим число, если оно делится на 5
    if k % 5 == 0:
        print(k)
    k = k + 1  # переходим к проверке следующего числа

# Все числа, кратные 5, отличаются друг от друга ровно на 5 => решение можно записать и без условия:
n = int(input())
k = 5  # начинаем проверять с первого числа, которое делится на 5
# повторяем действия, пока не дойдём до n => пока k <= n
while k <= n:
    # выводим число и увеличиваем его ровно на 5 (переходим к следующему, кратному 5)
    print(k)
    k = k + 5

