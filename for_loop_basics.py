# Перебор символов строки в цикле for
# Задача: посчитать, сколько букв а в строке

# считываем строку с экрана
stroka = input()
count = 0  # переменная для количества букв а
# здесь stroka - это последовательность символов
# каждый символ обозначается переменной char
for char in stroka:
    if char == 'а':  # проверяем, что текущий символ - это буква а
        count += 1
print(count)
