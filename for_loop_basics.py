# Примеры задач:

# Задача: вывести целые числа от 1 до n
# считываем целое число с экрана
n = int(input())
# формируем последовательность от 1 до n включительно
for i in range(1, n + 1):
    print(i, end=' ')


# Задача: вывести все числа от A до B, которые делятся на 3
a, b = map(int, input().split())
# формируем последовательность от A до B включительно
for i in range(a, b + 1):
    # проверяем, что число i делится на 3
    if i % 3 == 0:
        print(i, end=' ')


# Задача: вывести сумму всех четных чисел от A до B
a, b = map(int, input().split())
s = 0  # переменная для суммы
# формируем последовательность от A до B включительно
for i in range(a, b + 1):
    # проверяем, что число i четное
    if i % 2 == 0:
        s += i  # прибавляем число к сумме
print(s)

# Решение без условия
a, b = map(int, input().split())
s = 0
a = a + (a % 2)  # делаем число A четным
# перебираем все числа с шагом два (то есть все четные)
for i in range(a, b + 1, 2):
    s += i
print(s)

