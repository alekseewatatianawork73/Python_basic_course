# Цикл for. Функция range. Примеры задач.
#--------------------------------------------------------------------------------------------------
# синтаксис цикла: for переменная in последовательность
# действия выполняются для каждого элемента последовательности
# в цикле вместо элементов используется переменная x
for x in 11, 222, 33333, 'abc', 'def':
    print(x)

#--------------------------------------------------------------------------------------------------

# примеры формирования последовательности при помощи range()
# четные числа от 1 до 100
for i in range(2, 101, 2):
    print(i)

# нечетные числа от 100 до 1
for i in range(99, 0, -2):
    print(i)

# числа от 1 до 100, которые делятся на 10
for i in range(10, 101, 10):
    print(i)
